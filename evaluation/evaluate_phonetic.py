"""Evaluation of the phonetic correction layer: original vs guarded behaviour.

Three test sets:
  A. Misspellings of the 24 covered cities, generated by five noise types that are
     independent of the hand-written TRANSLITERATIONS table (those variants are
     exact lookups, so they are excluded).                      -> should be corrected
  B. Real Indian cities in OTHER_INDIAN_CITIES (seen by the guard). -> should be left alone
  C. Real Indian cities in NEITHER list (never seen by the guard;
     the honest test of false corrections).                     -> should be left alone

Run from the repository root:  python -m evaluation.evaluate_phonetic
"""
import json
import os
import random

from geoparse.data.address_components import CITIES, OTHER_INDIAN_CITIES, TRANSLITERATIONS
from geoparse.phonetic.corrector import PhoneticCorrector

OUT_DIR = os.path.dirname(os.path.abspath(__file__))
VOWELS = "aeiou"
PHONETIC_SWAPS = [("u", "oo"), ("oo", "u"), ("v", "w"), ("w", "v"), ("sh", "s"), ("th", "t"),
                  ("ee", "i"), ("i", "ee"), ("a", "aa"), ("aa", "a"), ("k", "c"), ("c", "k"),
                  ("ph", "f"), ("bh", "b"), ("dh", "d")]

# Set C: real Indian cities deliberately kept OUT of both dictionaries.
UNSEEN_CITIES = [
    "Hosur", "Sivakasi", "Karimnagar", "Nizamabad", "Bathinda", "Hoshiarpur", "Haridwar",
    "Rishikesh", "Alwar", "Bharatpur", "Sikar", "Satna", "Rewa", "Sagar", "Katni", "Ratlam",
    "Dewas", "Raigarh", "Korba", "Sambalpur", "Balasore", "Berhampur", "Puri", "Hazaribagh",
    "Deoghar", "Purnia", "Begusarai", "Arrah", "Etawah", "Hapur", "Rampur", "Sitapur",
    "Davangere", "Shivamogga", "Tumakuru", "Hassan", "Udupi", "Kottayam", "Kollam",
    "Palakkad", "Thanjavur", "Dindigul", "Karur", "Nagercoil", "Ongole", "Eluru",
    "Anantapur", "Latur", "Nanded", "Akola", "Ahmednagar", "Satara", "Bhuj", "Anand",
    "Bharuch", "Navsari", "Valsad", "Morbi", "Mehsana", "Junagadh",
]


def make_noise(word: str, rng: random.Random):
    """Five noise types; each keeps the first character, like most real typos."""
    def vowel_drop(w): return w[0] + "".join(c for c in w[1:] if c not in VOWELS)
    def deletion(w): i = rng.randrange(1, len(w)); return w[:i] + w[i + 1:]
    def swap(w): i = rng.randrange(1, len(w) - 1); return w[:i] + w[i + 1] + w[i] + w[i + 2:]
    def substitution(w): i = rng.randrange(1, len(w)); return w[:i] + rng.choice("abcdefghijklmnopqrstuvwxyz") + w[i + 1:]

    def phonetic(w):
        opts = [(a, b) for a, b in PHONETIC_SWAPS if a in w[1:]]
        if not opts:
            return None
        a, b = rng.choice(opts)
        i = w.index(a, 1)
        return w[:i] + b + w[i + len(a):]

    return {"vowel_drop": vowel_drop, "char_deletion": deletion, "adjacent_swap": swap,
            "random_substitution": substitution, "phonetic_respelling": phonetic}


def build_misspellings(seed: int = 7):
    rng = random.Random(seed)
    names = [c["name"] for c in CITIES]
    exclude = {v.lower() for vs in TRANSLITERATIONS.values() for v in vs} | {n.lower() for n in names}
    exclude |= {c.lower() for c in OTHER_INDIAN_CITIES + UNSEEN_CITIES}
    tests = []
    for name in names:
        for kind, fn in make_noise(name.lower(), rng).items():
            for _ in range(4):
                q = fn(name.lower())
                if q and q not in exclude:
                    tests.append((kind, q, name))
    return list(dict.fromkeys(tests))


def evaluate(corrector: PhoneticCorrector, misspellings):
    def changed(cities):
        return [(c, corrector.correct_city(c)[0]) for c in cities if corrector.correct_city(c)[0] != c]

    by_kind = {}
    for kind in sorted({k for k, _, _ in misspellings}):
        sub = [(q, g) for k, q, g in misspellings if k == kind]
        by_kind[kind] = round(sum(corrector.correct_city(q)[0] == g for q, g in sub) / len(sub), 3)
    acc = sum(corrector.correct_city(q)[0] == g for _, q, g in misspellings) / len(misspellings)
    seen, unseen = changed(OTHER_INDIAN_CITIES), changed(UNSEEN_CITIES)
    return {
        "A_misspelling_correction_accuracy": round(acc, 3),
        "A_accuracy_by_noise_type": by_kind,
        "B_false_corrections_known_other_cities": f"{len(seen)}/{len(OTHER_INDIAN_CITIES)}",
        "C_false_corrections_unseen_cities": f"{len(unseen)}/{len(UNSEEN_CITIES)}",
        "C_examples": [f"{a} -> {b}" for a, b in unseen[:10]],
    }


if __name__ == "__main__":
    tests = build_misspellings()
    results = {"n_misspellings": len(tests),
               "original": evaluate(PhoneticCorrector(guard_false_corrections=False), tests),
               "guarded": evaluate(PhoneticCorrector(guard_false_corrections=True), tests)}
    print(json.dumps(results, indent=1))
    with open(os.path.join(OUT_DIR, "phonetic_results.json"), "w") as f:
        json.dump(results, f, indent=1)
